def grade_at(t):
    """色彩暗线：这片土地是灰蓝的；出逃之后，颜色回来。"""
    if t < 6.0 or t >= 106.5:
        return dict(sat=1.0, dark=0.0, warm=0.0)
    if t < 61.0:
        return dict(sat=0.12, dark=0.0, warm=0.0)
    if t < 85.5:
        d = 0.0 if t < 75 else lerp(0.0, 0.12, prog(t, 75, 5)) + lerp(0, 0.25, ease_io(prog(t, 80, 5.5)))
        return dict(sat=0.08, dark=d, warm=0.0)
    if t < 103.0:
        return dict(sat=0.3, dark=0.0, warm=0.3)
    return dict(sat=0.3, dark=0.0, warm=0.3)
