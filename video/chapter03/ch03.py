def grade_at(t):
    """色彩一路渐变：灰 → 一点点回暖 → 彩色，不分块突变。“重锤”一节：夜里最灰，天亮以后慢慢回暖。"""
    if t < 6.0 or t >= 204.0:
        return dict(sat=1.0, dark=0.0, warm=0.0)
    if t < 41.0:
        return dict(sat=lerp(0.3, 0.42, prog(t, 6.0, 35.0)), dark=0.0, warm=0.0)
    if t < 60.0:
        return dict(sat=lerp(0.45, 0.55, prog(t, 41.0, 19.0)), dark=0.0, warm=0.04)
    if t < 78.0:
        return dict(sat=0.5, dark=0.04, warm=0.0)
    if t < 104.0:
        return dict(sat=lerp(0.5, 0.62, prog(t, 78.0, 26.0)), dark=0.0, warm=0.06)
    if t < 118.0:
        return dict(sat=lerp(0.62, 1.0, ease_io(prog(t, 104.0, 7.0))), dark=0.0, warm=0.08)
    return dict(sat=1.0, dark=0.0, warm=lerp(0.08, 0.14, prog(t, 150.0, 54.0)))
