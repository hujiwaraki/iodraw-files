def grade_at(t):
    """色彩：手账的暖 → 灰色的辛苦 → 有点暖的游客 → 世界展开 → 彩色的当地生活 → 合上手账。"""
    if t < 6.0 or t >= 159.0:
        return dict(sat=1.0, dark=0.0, warm=0.0)
    if t < 14.0:
        return dict(sat=lerp(0.85, 0.4, ease_io(prog(t, 8.4, 2.0))), dark=0.0, warm=0.15)
    if t < 39.0:
        return dict(sat=0.3, dark=0.0, warm=0.0)
    if t < 59.0:
        return dict(sat=0.5, dark=0.0, warm=0.05)
    if t < 66.0:
        return dict(sat=lerp(0.55, 1.0, ease_io(prog(t, 59.0, 5.0))), dark=0.0, warm=0.1)
    if t < 148.0:
        return dict(sat=1.0, dark=0.0, warm=0.08)
    return dict(sat=0.95, dark=0.0, warm=0.2)
