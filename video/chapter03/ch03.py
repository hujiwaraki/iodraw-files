def grade_at(t):
    """色彩一路渐变：灰 → 一点点回暖 → 彩色。夜里那两场最灰；一次次出发以后慢慢回暖。"""
    if t < 6.0 or t >= 211.5:
        return dict(sat=1.0, dark=0.0, warm=0.0)
    if t < 44.0:
        return dict(sat=0.32, dark=0.03, warm=0.0)
    if t < 61.0:
        return dict(sat=lerp(0.36, 0.42, prog(t, 44.0, 17.0)), dark=0.0, warm=0.0)
    if t < 80.0:
        return dict(sat=lerp(0.45, 0.55, prog(t, 61.0, 19.0)), dark=0.0, warm=0.04)
    if t < 99.0:
        return dict(sat=lerp(0.55, 0.65, prog(t, 80.0, 19.0)), dark=0.0, warm=0.06)
    if t < 125.5:
        return dict(sat=lerp(0.65, 1.0, ease_io(prog(t, 99.0, 7.0))), dark=0.0, warm=0.08)
    return dict(sat=1.0, dark=0.0, warm=lerp(0.08, 0.14, prog(t, 157.5, 54.0)))
