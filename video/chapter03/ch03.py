def grade_at(t):
    """色彩一路渐变：灰 → 一点点回暖 → 彩色，不分块突变。"""
    if t < 6.0 or t >= 160.0:
        return dict(sat=1.0, dark=0.0, warm=0.0)
    if t < 41.0:
        return dict(sat=lerp(0.3, 0.42, prog(t, 6.0, 35.0)), dark=0.0, warm=0.0)
    if t < 60.0:
        return dict(sat=lerp(0.45, 0.55, prog(t, 41.0, 19.0)), dark=0.0, warm=0.04)
    if t < 74.0:
        return dict(sat=lerp(0.6, 1.0, ease_io(prog(t, 60.0, 7.0))), dark=0.0, warm=0.08)
    return dict(sat=1.0, dark=0.0, warm=lerp(0.08, 0.14, prog(t, 106.0, 54.0)))
